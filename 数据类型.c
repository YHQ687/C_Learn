#include<stdio.h>
#include<stdbool.h>
/*
 * 数据类型：
 * 内置数据类型：整型(int)、浮点型[float,double,long double]、字符型[char]、布尔类型[_Bool]、
 * 自定义数据类型：数组、结构体-struct、枚举-enum、共用体-union、指针-pointer
 * 结构体是一种由用户自定义的新的数据类型，它可以包含不同类型的成员变量。将多个不同类型的数据组合在一起，形成一个整体。结构体的定义使用关键字struct。
 */

/*
//字符型：[]内可省略。
[signed] char;		//有符号字符型，范围[-128, 127]，占1个字节]
unsigned char;		//无符号字符型，范围[0, 255]，占1个字节]

//整型：[]内可省略。
[signed] int;		//有符号整型，范围[-2147483648, 2147483647]，占4个字节	
unsigned int;		//无符号整型，范围[0, 4294967295]，占4个字节
//短整型：short int;	//有符号短整型，范围[-32768, 32767]，占2个字节
//长整型：long int;	//有符号长整型，范围[-2147483648, 2147483647]，占4个字节
//长长整型：long long int;	//有符号长长整型，范围[-9223372036854775808, 9223372036854775807]，占8个字节

//浮点型：[]内可省略。
 float;			//单精度浮点型，范围[1.17549e-38, 3.40282e+38]，占4个字节
 double;		//双精度浮点型，范围[2.22507e-308, 1.79769e+308]，占8个字节
 long double;	//长双精度浮点型，范围[3.3621e-4932, 1.18973e+4932]，占16个字节

//布尔类型：需要使用头文件#include<stdbool.h>，否则会报错。
_Bool;	//布尔类型，取值为0（false）或1（true），占1个字节
*/

int main() {
	//定义变量
	char c = 'A';	//字符型变量c，初始化为'A'
	int i = 10;		//整型变量i，初始化为10
	float f = 3.14;	//浮点型变量f，初始化为3.14
	double d = 3.141592653589793;	//双精度浮点型变量d，初始化为3.141592653589793
	
	//输出变量的值和大小
	printf("字符型变量c的值: %c, 大小: %zu字节\n", c, sizeof(c));
	printf("整型变量i的值: %d, 大小: %zu字节\n", i, sizeof(i));
	printf("浮点型变量f的值: %.2f, 大小: %zu字节\n", f, sizeof(f));
	printf("双精度浮点型变量d的值: %.15f, 大小: %zu字节\n", d, sizeof(d));
	bool flag = true;	//布尔类型变量flag，初始化为true
	if (flag)
	
		printf("布尔类型变量flag的值: %d, 大小: %zu字节\n", flag, sizeof(flag));

	else

		printf("布尔类型变量flag的值: %d, 大小: %zu字节\n", flag, sizeof(flag));
	
}
